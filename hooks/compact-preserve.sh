#!/usr/bin/env bash
# PreCompact で、要約(compact)に残すべき項目をコンテキストに注入する。
# 要約処理を機械的に変えるものではなく、要約者へのガイダンスとして働く。
set -euo pipefail

cat <<'EOF'
[turntup:handoff] これからコンテキストが要約されます。要約には以下を必ず残してください:
- 現在のゴールと、進行中タスクがどこまで完了したか
- 重要ファイルの path:line と、その箇所で何をしていたか
- 決定事項とその理由
- 次にやるべき 1 アクション
要約後の作業状態消失に備え、区切りの良いタイミングで handoff Skill（引き継ぎ書の保存）の実行を提案してください。
EOF
